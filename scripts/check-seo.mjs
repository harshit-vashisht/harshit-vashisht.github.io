import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const read = name => readFile(new URL('../dist/' + name, import.meta.url), 'utf8');
const html = await read('index.html');
const origin = 'https://harshit-vashisht.github.io/';
assert.match(html, /<h1[^>]*>/);
for (const text of ['construction.', 'Forma', 'Orbit', 'Syntax', 'React', 'TypeScript', 'harshit-vashisht']) assert.ok(html.includes(text), `Missing crawlable content: ${text}`);
assert.equal((html.match(/rel="canonical"/g) || []).length, 1);
assert.match(html, new RegExp(`rel="canonical" href="${origin.replaceAll('.', '\\.')}"`));
assert.match(html, /name="author" content="harshit-vashisht, atulhacks"/);
assert.match(html, /name="robots" content="index, follow, max-image-preview:large"/);
for (const field of ['og:title', 'og:description', 'og:url', 'og:image', 'og:image:alt']) assert.ok(html.includes(`property="${field}"`));
const schema = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
assert.equal(schema['@context'], 'https://schema.org');
assert.equal(schema['@graph'].find(item => item['@type'] === 'Person').name, 'harshit-vashisht');
assert.equal(schema['@graph'].find(item => item['@type'] === 'ProfilePage').url, origin);
assert.ok((await read('robots.txt')).includes(`Sitemap: ${origin}sitemap.xml`));
assert.ok((await read('sitemap.xml')).includes(`<loc>${origin}</loc>`));
assert.match(await read('compare.html'), /content="noindex, follow"/);
assert.match(await read('404.html'), /content="noindex"/);
const image = await readFile(new URL('../dist/og-image.png', import.meta.url));
assert.equal(image.toString('hex', 0, 8), '89504e470d0a1a0a');
assert.equal(image.readUInt32BE(16), 1200);
assert.equal(image.readUInt32BE(20), 630);
console.log('SEO build checks passed: static content, canonical, identity, schema, social image, sitemap and index controls.');
